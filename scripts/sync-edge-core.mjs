#!/usr/bin/env node
// Generates supabase/functions/_shared/app-core.js from src/App.jsx.
//
// The Edge Functions need a handful of pure helpers (performance aggregation, fixture layout,
// threshold lookup...) that the React app already owns. Rather than hand-copying them — and
// letting the two copies drift — this pulls the exact declarations out of App.jsx, along with
// anything they transitively reference, and writes them as an ES module.
//
//   node scripts/sync-edge-core.mjs           regenerate app-core.js
//   node scripts/sync-edge-core.mjs --check   exit 1 if app-core.js is stale (use in CI)
//
// Only declarations that start at column 0 (`function x`, `const x =`) are recognized — the
// same style App.jsx already uses for its top-level helpers.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appPath = path.join(root, "src/App.jsx");
const outPath = path.join(root, "supabase/functions/_shared/app-core.js");

// What the edge agents call directly; their own dependencies (uid, DEFAULT_RESET_THRESHOLDS...)
// are pulled in automatically.
const ROOTS = [
  "uid",
  "getAttrByLabel",
  "getLatestWeekEnding",
  "getCutoffISO",
  "aggregateProductPerformanceRange",
  "getPlacementSpaceIn",
  "getEffectiveDims",
  "getStackDims",
  "getShelfClearanceIn",
  "getStackHeightProblem",
  "getStackDepthProblem",
  "getStackDepthProblem",
  "getAutoStackHigh",
  "getDosTargetDays",
  "getDaysOfSupply",
  "getCasePackFill",
  "DOS_EXCESS_FACTOR",
  "refitAutoStacks",
  "layoutFixtureBoxes",
  "getResetThreshold",
  "applyResetDraftChanges",
  "makePlanogramVersion",
  "effectivePlanogramStatus",
  "getFamilyMasterId",
  "getFamilyMembers",
  "getPredecessorPlanogram",
  "HELP_SECTIONS",
];

const lines = fs.readFileSync(appPath, "utf8").split("\n");

const decls = {};
let cur = null;
lines.forEach((l, i) => {
  const m = l.match(/^(?:async\s+)?function\s+([A-Za-z0-9_]+)|^const\s+([A-Za-z0-9_]+)\s*=/);
  if (m) {
    cur = m[1] || m[2];
    decls[cur] = { start: i, end: i };
  } else if (l.trim() && /^\S/.test(l) && !/^[})\]]/.test(l)) {
    cur = null; // a comment or other top-level statement ends the previous declaration
  }
  if (cur) decls[cur].end = i;
});

// leading comment lines directly above a declaration travel with it
const withComments = (name) => {
  let s = decls[name].start;
  while (s > 0 && /^\s*\/\//.test(lines[s - 1])) s--;
  return lines.slice(s, decls[name].end + 1).join("\n");
};

const needed = new Set();
const queue = [...ROOTS];
while (queue.length) {
  const n = queue.pop();
  if (needed.has(n)) continue;
  if (!decls[n]) {
    console.error(`sync-edge-core: ${n} not found at top level of src/App.jsx`);
    process.exit(2);
  }
  needed.add(n);
  const body = lines.slice(decls[n].start, decls[n].end + 1).join("\n");
  for (const other of Object.keys(decls)) {
    if (other !== n && !needed.has(other) && new RegExp(`\\b${other}\\b`).test(body)) queue.push(other);
  }
}

const ordered = [...needed].sort((a, b) => decls[a].start - decls[b].start);
const output = [
  "// GENERATED by scripts/sync-edge-core.mjs from src/App.jsx — do not edit by hand.",
  "// Edit the originals in src/App.jsx, then run: node scripts/sync-edge-core.mjs",
  "",
  ...ordered.map(withComments).flatMap((b) => [b, ""]),
  `export { ${ordered.join(", ")} };`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (existing !== output) {
    console.error("supabase/functions/_shared/app-core.js is out of date with src/App.jsx — run: node scripts/sync-edge-core.mjs");
    process.exit(1);
  }
  console.log(`app-core.js is up to date (${ordered.length} declarations).`);
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, output);
  console.log(`wrote ${path.relative(root, outPath)} (${ordered.length} declarations: ${ordered.join(", ")})`);
}
